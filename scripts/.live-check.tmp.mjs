// Test mot den publiserte siden: sjekker sikkerheten utenfra og sender ett tydelig merket testsvar via skjemaet.
import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const SITE = 'https://felovax.github.io/AtlasD-p/';
const html = await (await fetch(SITE)).text();
const main = html.match(/assets\/main-[^"]+\.js/)[0];
const js = await (await fetch(SITE + main)).text();
const url = (js.match(/https:\/\/[a-z0-9]+\.supabase\.co/) || [])[0];
const key = (js.match(/sb_publishable_[A-Za-z0-9_-]+/) || js.match(/eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/) || [])[0];
console.log('Supabase-adresse i siden:', url ? url.replace(/\/\/(.{4}).*\.supabase/, '//$1…supabase') : 'MANGLER');
console.log('Offentlig nøkkel i siden:', key ? key.slice(0, 15) + '…' : 'MANGLER');
console.log('Hemmelig nøkkel i siden:', /sb_secret|service_role/.test(js) ? 'JA – FEIL!' : 'nei (bra)');
if (!url || !key) process.exit(1);
const h = { apikey: key, ...(key.startsWith('eyJ') ? { Authorization: `Bearer ${key}` } : {}) };
const read = await fetch(`${url}/rest/v1/rsvps?select=*`, { headers: h });
console.log('Gjest prøver å lese svar →', read.status, (await read.text()).slice(0, 90));
const adm = await fetch(`${url}/rest/v1/rpc/is_admin`, { method: 'POST', headers: { ...h, 'Content-Type': 'application/json' }, body: '{}' });
console.log('Gjest prøver is_admin →', adm.status, (await adm.text()).slice(0, 90));
const bad = await fetch(`${url}/rest/v1/rpc/submit_rsvp`, { method: 'POST', headers: { ...h, 'Content-Type': 'application/json' }, body: JSON.stringify({ p_id: crypto.randomUUID(), p_attending: true, p_guest_count: 3, p_primary_name: 'Ugyldig' }) });
console.log('Ugyldig svar (3 personer) →', bad.status, (await bad.text()).slice(0, 90));

const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'nb-NO' });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(SITE, { waitUntil: 'networkidle' });
await p.evaluate(() => document.getElementById('svar').scrollIntoView({ behavior: 'instant' }));
await p.waitForTimeout(800);
await p.getByText('Nei, jeg kan dessverre ikke komme').tap();
await p.getByLabel('Navn', { exact: true }).fill('TEST fra Claude – slett meg');
const resp = p.waitForResponse((r) => r.url().includes('/rpc/submit_rsvp'));
await p.getByRole('button', { name: 'Send svar' }).tap();
const r = await resp;
console.log('Testsvar via skjemaet → HTTP', r.status(), await r.text());
await p.getByText('Takk for at du ga beskjed!').waitFor({ timeout: 10000 });
await p.evaluate(() => document.querySelector('.rsvp__card').scrollIntoView({ block: 'center', behavior: 'instant' }));
await p.waitForTimeout(600);
await p.screenshot({ path: process.argv[2] + '/live-testsvar.png' });
console.log('Takkemelding vist:', await p.locator('.rsvp__success-title').textContent());
console.log('Feil i konsollen:', errs.length ? errs : 'ingen');
await browser.close();
